// Embeds Leaflet into the app as plain strings so the map works with no CDN. Run `npm run
// map:assets` after changing the Leaflet version in package.json; the output
// (src/modules/map/leaflet.generated.ts) is committed, so a normal install never needs
// this.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dist = path.join(root, 'node_modules/leaflet/dist')
const version = JSON.parse(readFileSync(path.join(root, 'node_modules/leaflet/package.json'), 'utf8')).version

const guard = (source) => source.replace(/<\/script/gi, '<\\/script')

const out = `// GENERATED by scripts/build-map-assets.mjs. Do not edit by hand.
// Leaflet ${version}, BSD 2-Clause licence, (c) Vladimir Agafonkin and contributors.
// https://leafletjs.com/

export const LEAFLET_VERSION = ${JSON.stringify(version)}
export const LEAFLET_JS = ${JSON.stringify(guard(readFileSync(path.join(dist, 'leaflet.js'), 'utf8')))}
export const LEAFLET_CSS = ${JSON.stringify(readFileSync(path.join(dist, 'leaflet.css'), 'utf8'))}
`
writeFileSync(path.join(root, 'src/modules/map/leaflet.generated.ts'), out)
console.log(`Leaflet ${version} embedded (${Math.round(out.length / 1024)} KB)`)
